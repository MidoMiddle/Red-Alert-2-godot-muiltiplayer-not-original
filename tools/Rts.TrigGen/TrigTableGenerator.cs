using System;
using System.Globalization;
using System.Text;

namespace Rts.TrigGen;

/// <summary>
/// Builds the trigonometry tables of the simulation (docs/implementation/M2_unit_control.md, 4.1) with double precision and renders
/// them as C# integer literals. Runs on the developer's machine only; the simulation reads the committed integers, never doubles.
/// The test project links this file to check that the committed tables match what the generator produces.
/// </summary>
public static class TrigTableGenerator
{
    /// <summary>One full turn in <c>BAngle</c> units.</summary>
    public const int FullTurn = 65536;

    /// <summary>A quarter turn: the sine table covers 0°…90°.</summary>
    public const int QuarterTurn = FullTurn / 4;

    /// <summary>Angle step between two sine entries, in <c>BAngle</c> units.</summary>
    public const int SinStep = 4;

    /// <summary>Number of steps of the arctangent table over t = 0…1.</summary>
    public const int AtanSteps = 1024;

    /// <summary>One in the simulation's fixed-point format (<c>Fixed.OneRaw</c>).</summary>
    public const int FixedOne = 65536;

    /// <summary>sin(i · 4 BAngle units) as <c>Fixed.Raw</c>, i = 0…4096 (0°…90°).</summary>
    public static int[] SinQuarter()
    {
        var table = new int[QuarterTurn / SinStep + 1];
        for (var i = 0; i < table.Length; i++)
        {
            var radians = (double)i * SinStep / FullTurn * 2.0 * Math.PI;
            table[i] = (int)Math.Round(Math.Sin(radians) * FixedOne, MidpointRounding.AwayFromZero);
        }

        return table;
    }

    /// <summary>atan(j / 1024) in <c>BAngle</c> units, j = 0…1024 (0°…45°).</summary>
    public static ushort[] AtanTable()
    {
        var table = new ushort[AtanSteps + 1];
        for (var j = 0; j < table.Length; j++)
        {
            var angle = Math.Atan((double)j / AtanSteps) / (2.0 * Math.PI) * FullTurn;
            table[j] = (ushort)Math.Round(angle, MidpointRounding.AwayFromZero);
        }

        return table;
    }

    /// <summary>The full text of <c>src/Rts.Simulation/Math/TrigTables.cs</c>.</summary>
    public static string Render()
    {
        var text = new StringBuilder();
        text.Append("// <auto-generated-by-tool>\n");
        text.Append("// Generated by tools/Rts.TrigGen. Do not edit by hand: run the generator and commit the result.\n");
        text.Append("// The file name has no .g.cs on purpose, so the determinism analyzers still check it.\n");
        text.Append("// </auto-generated-by-tool>\n\n");
        text.Append("namespace Rts.Simulation.Math;\n\n");
        text.Append("/// <summary>Integer trigonometry tables (docs/implementation/M2_unit_control.md, 4.1).</summary>\n");
        text.Append("internal static class TrigTables\n{\n");
        text.Append("    /// <summary>sin(i · 4 BAngle units) as Fixed.Raw, i = 0…4096 (0°…90°).</summary>\n");
        AppendArray(text, "int", "SinQuarter", Array.ConvertAll(SinQuarter(), value => (long)value));
        text.Append('\n');
        text.Append("    /// <summary>atan(j / 1024) in BAngle units, j = 0…1024 (0°…45°).</summary>\n");
        AppendArray(text, "ushort", "Atan", Array.ConvertAll(AtanTable(), value => (long)value));
        text.Append("}\n");
        return text.ToString();
    }

    private static void AppendArray(StringBuilder text, string type, string name, long[] values)
    {
        const int PerLine = 16;
        text.Append($"    internal static readonly {type}[] {name} =\n    [\n");
        for (var i = 0; i < values.Length; i += PerLine)
        {
            text.Append("        ");
            for (var j = i; j < Math.Min(i + PerLine, values.Length); j++)
            {
                text.Append(values[j].ToString(CultureInfo.InvariantCulture)).Append(',');
                if (j + 1 < Math.Min(i + PerLine, values.Length))
                {
                    text.Append(' ');
                }
            }

            text.Append('\n');
        }

        text.Append("    ];\n");
    }
}
