using System.Text;

namespace Rts.Simulation.Benchmarks;

/// <summary>
/// The squad map of the M2 definition of done (docs/implementation/M2_unit_control.md, section 7): the sandbox with its blue
/// units replaced by a squad of 40 heavy tanks and 20 conscripts south of the forest, and a tree wall across the whole map at
/// row <see cref="WallRow"/> with a single gap at column <see cref="GapColumn"/>. Made from game/maps/test/sandbox.txt and
/// committed as game/maps/test/squad.txt; a test checks the two agree.
/// </summary>
public static class SquadMap
{
    public const string SandboxPath = "game/maps/test/sandbox.txt";
    public const string MapPath = "game/maps/test/squad.txt";

    public const int WallRow = 36;
    public const int GapColumn = 16;

    /// <summary>Tanks stand one per cell, 10 x 4 from (18, 19); the conscripts five to a cell east of them.</summary>
    public const int TankLeft = 18;
    public const int TankTop = 19;
    public const int TankColumns = 10;
    public const int TankRows = 4;
    public const int Tanks = 40;
    public const int Conscripts = 20;

    public static string Generate(string sandboxText)
    {
        var text = new StringBuilder();
        text.Append("// Squad map of M2 (docs/implementation/M2_unit_control.md, section 7): the sandbox with 40 heavy tanks and 20 conscripts\n");
        text.Append("// south of the forest and a tree wall across row 36 with one gap at column 16.\n");
        text.Append("// Generated by `dotnet run --project src/Rts.Simulation.Benchmarks -- --write-map` from sandbox.txt; do not edit by hand.\n");
        text.Append("// Codes: . clear  , rough  = road  b beach  ~ shallow  W deep  # rock  i ice  T tree\n");
        var row = 0;
        var objectLines = new List<string>();
        foreach (var raw in sandboxText.Replace("\r\n", "\n").Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("//", StringComparison.Ordinal))
            {
                continue;
            }

            if (line.StartsWith("object ", StringComparison.Ordinal))
            {
                // Map objects of the sandbox (M7 step 5) stay as they are.
                objectLines.Add(line);
                continue;
            }

            if (line.StartsWith("unit ", StringComparison.Ordinal))
            {
                // The red units stay; the blue ones give way to the squad.
                if (!line.EndsWith("player=1", StringComparison.Ordinal))
                {
                    text.Append(line).Append('\n');
                }

                continue;
            }

            if (row == WallRow)
            {
                var cells = line.Split(' ');
                for (var x = 0; x < cells.Length; x++)
                {
                    cells[x] = x == GapColumn ? "." : "T";
                }

                line = string.Join(' ', cells);
            }

            text.Append(line).Append('\n');
            row++;
        }

        foreach (var objectLine in objectLines)
        {
            text.Append(objectLine).Append('\n');
        }

        for (var i = 0; i < Tanks; i++)
        {
            text.Append($"unit heavy_tank {TankLeft + i % TankColumns} {TankTop + i / TankColumns} player=1\n");
        }

        for (var i = 0; i < Conscripts; i++)
        {
            text.Append($"unit conscript {TankLeft + TankColumns + i / 5} {TankTop + 1} player=1\n");
        }

        return text.ToString();
    }
}
