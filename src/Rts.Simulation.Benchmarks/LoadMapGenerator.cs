using System.Text;
using Rts.Simulation.World;

namespace Rts.Simulation.Benchmarks;

/// <summary>
/// Writes the load map of docs/implementation/M2_unit_control.md, 4.15: 128 x 128 cells with roads, forests, a lake with
/// shallows and beach, an ice pond, a rock ridge with four-cell passes, a 41 x 41 maze of tree walls in the north-east, and
/// 300 blue units in the west third (100 infantry, 150 tanks, 50 jeeps), one per cell, row by row. The output is committed
/// as game/maps/test/load128.txt; the generator is kept so it can be made again (fixed seed).
/// </summary>
public static class LoadMapGenerator
{
    public const int Size = 128;

    /// <summary>The maze: top-left tile, cells per side (each cell is two tiles plus a wall).</summary>
    public const int MazeLeft = 84;
    public const int MazeTop = 2;
    public const int MazeCells = 20;

    /// <summary>Units stand on a grid of 15 columns by 20 rows, every second cell from (6, 44).</summary>
    public const int UnitColumns = 15;
    public const int UnitRows = 20;
    public const int UnitLeft = 6;
    public const int UnitTop = 44;

    private const int Seed = 128;

    public static string Generate()
    {
        var map = new char[Size, Size];
        for (var y = 0; y < Size; y++)
        {
            for (var x = 0; x < Size; x++)
            {
                map[x, y] = '.';
            }
        }

        var random = new System.Random(Seed);
        for (var i = 0; i < Size; i++)
        {
            map[i, 64] = '=';
            map[60, i] = '=';
        }

        // Rough fields and forests: soft blobs.
        for (var blob = 0; blob < 10; blob++)
        {
            Blob(map, random, ',', 4 + random.Next(5));
        }

        for (var blob = 0; blob < 14; blob++)
        {
            Blob(map, random, 'T', 2 + random.Next(4));
        }

        // A lake with shallows and beach, and an ice pond.
        Disc(map, 60, 104, 12, 'b');
        Disc(map, 60, 104, 10, '~');
        Disc(map, 60, 104, 7, 'W');
        Disc(map, 112, 118, 5, 'i');

        // A rock ridge from north to south with three passes of four cells.
        for (var y = 30; y < 122; y++)
        {
            if (y is (>= 56 and < 60) or (>= 72 and < 76) or (>= 88 and < 92))
            {
                map[78, y] = map[79, y] = '.';
                continue;
            }

            map[78, y] = '#';
            map[79, y] = '#';
        }

        Maze(map, random);

        // The start area is open ground, so every unit has its cell.
        for (var y = UnitTop - 2; y < UnitTop + UnitRows * 2; y++)
        {
            for (var x = UnitLeft - 2; x < UnitLeft + UnitColumns * 2; x++)
            {
                map[x, y] = '.';
            }
        }

        // Lines end in \n on every system (not AppendLine): the committed file must match what any machine generates.
        var text = new StringBuilder();
        text.Append("// Load map of M2 step 15 (docs/implementation/M2_unit_control.md, 4.15): 128 x 128, 300 units.\n");
        text.Append("// Generated by `dotnet run --project src/Rts.Simulation.Benchmarks -- --write-map`; do not edit by hand.\n");
        text.Append("// Codes: . clear  , rough  = road  b beach  ~ shallow  W deep  # rock  i ice  T tree\n");
        for (var y = 0; y < Size; y++)
        {
            for (var x = 0; x < Size; x++)
            {
                text.Append(map[x, y]);
                text.Append(x == Size - 1 ? '\n' : ' ');
            }
        }

        for (var i = 0; i < UnitColumns * UnitRows; i++)
        {
            var x = UnitLeft + i % UnitColumns * 2;
            var y = UnitTop + i / UnitColumns * 2;
            text.Append($"unit {UnitIdAt(i)} {x} {y} player=1\n");
        }

        return text.ToString();
    }

    /// <summary>
    /// The type of the <paramref name="index"/>-th unit: of every six, two soldiers, three tanks and a jeep, so each row is
    /// mixed. Soldiers go conscript, rocketeer, engineer; every third tank is a Tesla tank.
    /// </summary>
    public static string UnitIdAt(int index)
    {
        var slot = index % 6;
        var round = index / 6;
        if (slot < 2)
        {
            var soldier = round * 2 + slot;
            return (soldier % 3) switch
            {
                0 => "conscript",
                1 => "rocketeer",
                _ => "engineer",
            };
        }

        if (slot < 5)
        {
            var tank = round * 3 + slot - 2;
            return tank % 3 == 2 ? "tesla_tank" : "heavy_tank";
        }

        return "support_vehicle";
    }

    private static void Blob(char[,] map, System.Random random, char code, int radius)
    {
        // Keep the blobs off the maze, the ridge and the lake, so those stay as designed.
        int cx;
        int cy;
        do
        {
            cx = 4 + random.Next(Size - 8);
            cy = 4 + random.Next(Size - 8);
        }
        while (cx > MazeLeft - 8 && cy < MazeTop + MazeCells * 2 + 8);

        for (var y = cy - radius; y <= cy + radius; y++)
        {
            for (var x = cx - radius; x <= cx + radius; x++)
            {
                var dx = x - cx;
                var dy = y - cy;
                if (x >= 0 && y >= 0 && x < Size && y < Size && dx * dx + dy * dy <= radius * radius + random.Next(radius + 1)
                    && map[x, y] == '.')
                {
                    map[x, y] = code;
                }
            }
        }
    }

    private static void Disc(char[,] map, int cx, int cy, int radius, char code)
    {
        for (var y = cy - radius; y <= cy + radius; y++)
        {
            for (var x = cx - radius; x <= cx + radius; x++)
            {
                if (x >= 0 && y >= 0 && x < Size && y < Size && (x - cx) * (x - cx) + (y - cy) * (y - cy) <= radius * radius)
                {
                    map[x, y] = code;
                }
            }
        }
    }

    /// <summary>A perfect maze (depth-first, fixed seed) of tree walls; its door is in the middle of the west side.</summary>
    private static void Maze(char[,] map, System.Random random)
    {
        var side = MazeCells * 2 + 1;
        for (var y = 0; y < side; y++)
        {
            for (var x = 0; x < side; x++)
            {
                map[MazeLeft + x, MazeTop + y] = 'T';
            }
        }

        var visited = new bool[MazeCells, MazeCells];
        var stack = new Stack<(int X, int Y)>();
        stack.Push((0, 0));
        visited[0, 0] = true;
        Open(map, 0, 0);
        (int, int)[] steps = [(0, -1), (1, 0), (0, 1), (-1, 0)];
        while (stack.Count > 0)
        {
            var (x, y) = stack.Peek();
            var options = steps.Where(s => x + s.Item1 is >= 0 and < MazeCells && y + s.Item2 is >= 0 and < MazeCells
                && !visited[x + s.Item1, y + s.Item2]).ToList();
            if (options.Count == 0)
            {
                stack.Pop();
                continue;
            }

            var (dx, dy) = options[random.Next(options.Count)];
            map[MazeLeft + 1 + x * 2 + dx, MazeTop + 1 + y * 2 + dy] = '.';
            visited[x + dx, y + dy] = true;
            Open(map, x + dx, y + dy);
            stack.Push((x + dx, y + dy));
        }

        map[MazeLeft, MazeTop + 1 + MazeCells / 2 * 2] = '.';
    }

    private static void Open(char[,] map, int x, int y) => map[MazeLeft + 1 + x * 2, MazeTop + 1 + y * 2] = '.';
}
